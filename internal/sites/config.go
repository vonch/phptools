var domainPattern = regexp.MustCompile(`^(?:[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?\.)+[a-z][a-z0-9-]{0,62}$`)
var idPattern = regexp.MustCompile(`^[A-Za-z0-9_-]+$`)

func ValidDomain(v string) bool {
	return v == "localhost" || len(v) <= 253 && domainPattern.MatchString(v)
}

func Validate(site model.Site, others []model.Site, instances []model.Instance) (model.Site, error) {
	site.Domain = strings.ToLower(strings.TrimSpace(site.Domain))
	site.Name = strings.TrimSpace(site.Name)
	if !idPattern.MatchString(site.ID) {
		return site, errors.New("站点 ID 无效")
	}
	if site.Name == "" {
		site.Name = site.Domain
	}
	if !ValidDomain(site.Domain) {
		return site, errors.New("请输入有效域名，例如 demo.test")
	}
	if site.Port < 1 || site.Port > 65535 {
		return site, errors.New("站点端口应在 1–65535 之间")
	}
	if !filepath.IsAbs(site.Root) || strings.ContainsAny(site.Root, "\r\n\"\x00") {
		return site, errors.New("项目目录必须是有效绝对路径")
	}
	info, err := os.Stat(site.Root)
	if err != nil || !info.IsDir() {
		return site, errors.New("项目目录不存在")
	}
	site.Root = filepath.Clean(site.Root)
	if filepath.IsAbs(site.Entry) {
		return site, errors.New("入口目录必须相对于项目目录")
	}
	if strings.ContainsAny(site.Entry, "\r\n\"\x00") {
		return site, errors.New("入口目录不能超出项目目录")
	}
	site.Entry, err = RelativeEntry(site.Root, filepath.Join(site.Root, site.Entry))
	if err != nil {
		return site, err
	}
	for _, v := range others {
		if v.ID != site.ID && v.Domain == site.Domain && v.Port == site.Port {
			return site, errors.New("该域名与端口已有站点")
		}
	}
	if site.PHPInstanceID != "" {
		found := false
		for _, v := range instances {
			if v.ID == site.PHPInstanceID && v.Kind == "php" {
				found = true
			}
		}
		if !found {
			return site, errors.New("所选 PHP 实例不存在")
		}
	}
	if strings.ContainsRune(site.Rewrite, 0) {
		return site, errors.New("伪静态规则包含无效字符")
	}
	if site.Enabled && (site.HTTPS || site.Port == 443) {
		for _, v := range others {
			if v.ID != site.ID && v.Enabled && v.Domain == site.Domain && (v.HTTPS || v.Port == 443) {
				return site, errors.New("这个域名已经有使用 443 端口的站点")
			}
		}
	}
	return site, nil
}

func Render(root string, site model.Site, php *model.Instance) string {
	quote := func(v string) string { return `"` + strings.ReplaceAll(filepath.ToSlash(v), "$", `\$`) + `"` }
	var b strings.Builder
	fmt.Fprintf(&b, "# Generated by PHPTools: %s\nserver {\n", site.ID)
	if site.HTTPS && idPattern.MatchString(site.ID) {
		cert, key := certificatePaths(root, site.ID)
		if site.Port != 443 {
			fmt.Fprintf(&b, "    listen 127.0.0.1:%d;\n", site.Port)
		}
		fmt.Fprintf(&b, "    listen 127.0.0.1:443 ssl;\n    ssl_certificate %s;\n    ssl_certificate_key %s;\n    ssl_protocols TLSv1.2 TLSv1.3;\n", quote(cert), quote(key))
	} else {
		fmt.Fprintf(&b, "    listen 127.0.0.1:%d;\n", site.Port)
	}
	fmt.Fprintf(&b, "    server_name %s;\n    root %s;\n    index index.php index.html;\n    access_log %s;\n    error_log %s;\n", site.Domain, quote(filepath.Join(site.Root, site.Entry)), quote(filepath.Join(root, "logs", site.ID+"-access.log")), quote(filepath.Join(root, "logs", site.ID+"-error.log")))
	if strings.TrimSpace(site.Rewrite) != "" {
		fmt.Fprintf(&b, "    # Custom rules\n%s\n", site.Rewrite)
	} else if php != nil {
		b.WriteString("    location / { try_files $uri $uri/ /index.php?$query_string; }\n")
	} else {
		b.WriteString("    location / { try_files $uri $uri/ =404; }\n")
	}
	httpsParam := ""
	if site.HTTPS {
		httpsParam = "        fastcgi_param HTTPS $https if_not_empty;\n"
	}
	if php != nil {
		if site.PHPPathInfo {
			fmt.Fprintf(&b, "    location ~ \\.php(.*)$ {\n        fastcgi_split_path_info ^((?U).+\\.php)(/?.+)$;\n        fastcgi_pass 127.0.0.1:%d;\n        fastcgi_index index.php;\n        include fastcgi_params;\n        fastcgi_param SCRIPT_FILENAME $document_root$fastcgi_script_name;\n        fastcgi_param PATH_INFO $fastcgi_path_info;\n        fastcgi_param PATH_TRANSLATED $document_root$fastcgi_path_info;\n%s    }\n", php.Port, httpsParam)
		} else {
			fmt.Fprintf(&b, "    location ~ \\.php$ {\n        try_files $uri =404;\n        fastcgi_pass 127.0.0.1:%d;\n        fastcgi_index index.php;\n        include fastcgi_params;\n        fastcgi_param SCRIPT_FILENAME $document_root$fastcgi_script_name;\n%s    }\n", php.Port, httpsParam)
		}
	} else {
		b.WriteString("    location ~ \\.php$ { return 403; }\n")
	}
	b.WriteString("    location ~ /\\. { deny all; }\n}\n")
	return b.String()
}

// Apply writes only owned .conf files; rollback restores the previous complete set.
func Apply(root string, all []model.Site, instances []model.Instance) (func() error, error) {
	dir := filepath.Join(root, "sites")
	old := map[string][]byte{}
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, err
	}
	for _, e := range entries {
		if !e.IsDir() && strings.HasSuffix(e.Name(), ".conf") {
			data, err := os.ReadFile(filepath.Join(dir, e.Name()))
			if err != nil {
				return nil, err
			}
			if !strings.HasPrefix(string(data), "# Generated by PHPTools:") {
				return nil, fmt.Errorf("站点目录存在未管理配置 %s", e.Name())
			}
			old[e.Name()] = data
		}
	}
	writeSet := func(files map[string][]byte) error {
		for _, e := range mustEntries(dir) {
			if strings.HasSuffix(e.Name(), ".conf") {
				if _, ok := files[e.Name()]; !ok {
					if err := os.Remove(filepath.Join(dir, e.Name())); err != nil {
						return err
					}
				}
			}
		}
		for name, data := range files {
			tmp := filepath.Join(dir, name+".tmp")
			if err := os.WriteFile(tmp, data, 0600); err != nil {
				return err
			}
			if err := os.Rename(tmp, filepath.Join(dir, name)); err != nil {
				return err
			}
		}
		return nil
	}
	next := map[string][]byte{}
	for _, s := range all {
		if !s.Enabled {
			continue
		}
		var php *model.Instance
		for i := range instances {
			if instances[i].ID == s.PHPInstanceID {
				php = &instances[i]
			}
		}
		if !idPattern.MatchString(s.ID) {
			return nil, errors.New("站点 ID 无效")
		}
		next[s.ID+".conf"] = []byte(Render(root, s, php))
	}
	rollback := func() error { return writeSet(old) }
	if err := writeSet(next); err != nil {
		_ = rollback()
		return nil, err
	}
	return rollback, nil
}

func mustEntries(dir string) []os.DirEntry { entries, _ := os.ReadDir(dir); return entries }

func Domains(all []model.Site) []string {
	set := map[string]bool{}
	for _, s := range all {
		if s.Enabled && s.Domain != "localhost" {
			set[s.Domain] = true
		}
	}
	out := []string{}
	for d := range set {
		out = append(out, d)
	}
	sort.Strings(out)
	return out
}

const hostsStart = "# BEGIN PHPTOOLS"
const hostsEnd = "# END PHPTOOLS"

func HostsContent(original []byte, domains []string) ([]byte, error) {
	text := string(original)
	if strings.HasPrefix(text, "\xff\xfe") || strings.HasPrefix(text, "\xfe\xff") {
		return nil, errors.New("hosts 使用 UTF-16 编码，请先转换为 UTF-8 后再配置站点")
	}
	wanted := map[string]bool{}
	for _, d := range domains {
		if !ValidDomain(d) {
			return nil, errors.New("hosts 域名无效")
		}
		wanted[d] = true
	}
	start, end, offset := -1, -1, 0
	inside := false
	for _, raw := range strings.SplitAfter(text, "\n") {
		line := strings.TrimPrefix(raw, "\ufeff")
		trimmed := strings.TrimSpace(line)
		switch trimmed {
		case hostsStart:
			if start >= 0 {
				return nil, errors.New("hosts 中 PHPTools 标记重复")
			}
			start = offset + len(raw) - len(line)
			inside = true
		case hostsEnd:
			if !inside {
				return nil, errors.New("hosts 中 PHPTools 标记不完整")
			}
			inside = false
			end = offset + len(raw)
		default:
			if !inside {
				beforeComment, _, _ := strings.Cut(line, "#")
				fields := strings.Fields(beforeComment)
				if len(fields) > 1 && fields[0] != "127.0.0.1" && fields[0] != "::1" {
					for _, name := range fields[1:] {
						if wanted[strings.ToLower(strings.TrimSuffix(name, "."))] {
							return nil, fmt.Errorf("hosts 中域名 %s 已有其他地址映射，请更换域名或手动处理原条目", name)
						}
					}
				}
			}
		}
		offset += len(raw)
	}
	if inside {
		return nil, errors.New("hosts 中 PHPTools 标记不完整")
	}
	block := ""
	if len(domains) > 0 {
		block = hostsStart + "\r\n"
		for _, d := range domains {
			block += "127.0.0.1 " + d + "\r\n"
		}
		block += hostsEnd + "\r\n"
	}
	if start >= 0 {
		return []byte(text[:start] + block + text[end:]), nil
	}
	if block == "" {
		return original, nil
	}
	if strings.HasPrefix(text, "\ufeff") {
		return []byte("\ufeff" + block + strings.TrimPrefix(text, "\ufeff")), nil
	}
	return []byte(block + text), nil
}

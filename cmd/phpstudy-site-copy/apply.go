func requireTargetClosed(ctx context.Context) error {
	const script = `$ErrorActionPreference='Stop'; if (Get-Process -Name PHPTools -ErrorAction SilentlyContinue) { throw 'Close PHPTools before applying sites' }; if (Get-CimInstance Win32_Process -Filter "Name = 'nginx.exe'" | Where-Object { $_.ExecutablePath -and $_.ExecutablePath.StartsWith('E:\PHPTools\',[StringComparison]::OrdinalIgnoreCase) }) { throw 'Target Nginx is running; sites were not changed' }`
	command := exec.CommandContext(ctx, "powershell.exe", "-NoProfile", "-NonInteractive", "-Command", script)
	command.SysProcAttr = &syscall.SysProcAttr{HideWindow: true, CreationFlags: 0x08000000}
	output, err := command.CombinedOutput()
	if err != nil {
		return fmt.Errorf("target safety check: %w: %s", err, output)
	}
	return nil
}

func applyTarget(ctx context.Context, root, planPath, validationPath string) (runErr error) {
	if filepath.Clean(root) != `E:\PHPTools` {
		return errors.New("this migration is limited to E:\\PHPTools")
	}
	if err := requireTargetClosed(ctx); err != nil {
		return err
	}
	var plan []model.Site
	var validated validationReport
	if err := readJSON(planPath, &plan); err != nil {
		return err
	}
	if err := readJSON(validationPath, &validated); err != nil {
		return err
	}
	digest, err := siteDigest(plan)
	if err != nil {
		return err
	}
	if len(plan) != 53 || !validated.Cleaned || validated.Error != "" || len(validated.Checks) < 5 || validated.PlanSHA256 != digest {
		return errors.New("the current site plan has not passed isolated acceptance")
	}
	db, err := store.Open(root)
	if err != nil {
		return err
	}
	defer func() { runErr = errors.Join(runErr, db.Close()) }()
	existing, err := store.List[model.Site](db, "site")
	if err != nil {
		return err
	}
	instances, err := store.List[model.Instance](db, "instance")
	if err != nil {
		return err
	}
	var nginx model.Instance
	for _, instance := range instances {
		if instance.Kind == "nginx" {
			if nginx.ID != "" || instance.PID != 0 {
				return errors.New("destination must have exactly one stopped Nginx instance")
			}
			nginx = instance
		}
	}
	if nginx.ID == "" {
		return errors.New("destination Nginx is missing")
	}
	byID := map[string]model.Site{}
	for _, site := range existing {
		byID[site.ID] = site
	}
	for _, site := range plan {
		validatedSite, err := sites.Validate(site, existing, instances)
		if err != nil {
			return err
		}
		byID[site.ID] = validatedSite
	}
	all := make([]model.Site, 0, len(byID))
	values := map[string]any{}
	for id, site := range byID {
		all = append(all, site)
		values[id] = site
	}
	if len(all) != 55 {
		return fmt.Errorf("destination site count changed: %d; review before applying", len(all))
	}
	mainBefore, err := os.ReadFile(nginx.ConfigPath)
	if err != nil {
		return err
	}
	mainAfter, err := sourceHTTPSettings(mainBefore)
	if err != nil {
		return err
	}
	backup, err := backupSites(root, nginx, mainBefore)
	if err != nil {
		return err
	}
	if err := requireTargetClosed(ctx); err != nil {
		return err
	}
	rollback, err := sites.Apply(root, all, instances)
	if err != nil {
		return err
	}
	committed := false
	defer func() {
		if !committed {
			runErr = errors.Join(runErr, rollback(), os.WriteFile(nginx.ConfigPath, mainBefore, 0600))
		}
	}()
	if err = os.WriteFile(nginx.ConfigPath, mainAfter, 0600); err != nil {
		return err
	}
	if err = nginxSyntax(ctx, nginx); err != nil {
		return err
	}
	if err = db.Replace("site", values); err != nil {
		return err
	}
	committed = true
	data, err := json.MarshalIndent(map[string]any{"completed": model.Now(), "backup": backup, "sites": len(all), "imported": len(plan), "planSHA256": digest, "syntaxPassed": true, "servicesChanged": false, "hostsChanged": false}, "", "  ")
	if err == nil {
		err = os.WriteFile(filepath.Join(filepath.Dir(planPath), "sites-apply-report.json"), data, 0600)
	}
	fmt.Printf("Applied %d sites after syntax validation; no service/hosts changes; backup: %s\n", len(all), backup)
	return err
}

func backupSites(root string, nginx model.Instance, mainConfig []byte) (string, error) {
	entries, err := os.ReadDir(filepath.Join(root, "sites"))
	if err != nil {
		return "", err
	}
	files := map[string][]byte{}
	for _, entry := range entries {
		if entry.IsDir() || !strings.HasSuffix(entry.Name(), ".conf") {
			continue
		}
		data, err := os.ReadFile(filepath.Join(root, "sites", entry.Name()))
		if err != nil {
			return "", err
		}
		if !strings.HasPrefix(string(data), "# Generated by PHPTools:") {
			return "", fmt.Errorf("unknown site configuration was preserved: %s", entry.Name())
		}
		files[entry.Name()] = data
	}
	backup, err := os.MkdirTemp(filepath.Join(root, "backups"), "phpstudy-sites-")
	if err != nil {
		return "", err
	}
	db, err := sql.Open("sqlite", "file:"+filepath.ToSlash(filepath.Join(root, "metadata.db"))+"?mode=ro")
	if err != nil {
		return "", err
	}
	defer db.Close()
	metadataPath := strings.ReplaceAll(filepath.ToSlash(filepath.Join(backup, "metadata-before.db")), "'", "''")
	if _, err = db.Exec("VACUUM INTO '" + metadataPath + "'"); err != nil {
		return "", err
	}
	if err = os.WriteFile(filepath.Join(backup, "nginx-before.conf"), mainConfig, 0600); err != nil {
		return "", err
	}
	if err = os.Mkdir(filepath.Join(backup, "sites"), 0700); err != nil {
		return "", err
	}
	for name, data := range files {
		if err = os.WriteFile(filepath.Join(backup, "sites", name), data, 0600); err != nil {
			return "", err
		}
	}
	return backup, nil
}
